import Foundation

public struct V2AgentConversationMessage: Codable, Equatable, Sendable {
    public enum Role: String, Codable, Equatable, Sendable {
        case user
        case assistant
    }

    public var role: Role
    public var text: String

    public init(role: Role, text: String) {
        self.role = role
        self.text = text
    }
}

public struct V2AgentObservation: Codable, Equatable, Sendable {
    public var sourceID: String
    public var tool: V2AgentTool
    public var summary: String

    public init(sourceID: String, tool: V2AgentTool, summary: String) {
        self.sourceID = sourceID
        self.tool = tool
        self.summary = summary
    }
}

/// Ephemeral provider continuation; never stored in the user's session or trace.
public struct V2AgentToolExchange: Equatable, Sendable {
    public var assistantMessage: Data
    public var results: [Result]
    public struct Result: Equatable, Sendable {
        public var callID: String
        public var content: String
        public init(callID: String, content: String) { self.callID = callID; self.content = content }
    }
    public init(assistantMessage: Data, results: [Result]) {
        self.assistantMessage = assistantMessage; self.results = results
    }
}

public struct V2AgentRequest: Equatable, Sendable {
    public var toolExchanges: [V2AgentToolExchange]
    public var userText: String
    public var conversation: [V2AgentConversationMessage]
    public var observations: [V2AgentObservation]
    public var conversationIdentifier: String?
    /// Whether the host currently exposes the independent, read-only web
    /// search/read capability. This is intentionally separate from the model
    /// provider: a provider does not get to infer web access from its own
    /// product features.
    public var webAvailable: Bool
    /// The per-turn catalog is generated by the host from active modules. It
    /// is part of the request so a provider never has to guess which command
    /// exists or is currently authorized.
    public var toolCatalog: V2ToolCatalog
    public var context: V2AssistantContext

    public init(
        userText: String,
        conversation: [V2AgentConversationMessage],
        observations: [V2AgentObservation],
        conversationIdentifier: String? = nil,
        webAvailable: Bool = true,
        toolCatalog: V2ToolCatalog = .empty,
        context: V2AssistantContext = .init(),
        toolExchanges: [V2AgentToolExchange] = []
    ) {
        self.toolExchanges = toolExchanges
        self.userText = userText
        self.conversation = conversation
        self.observations = observations
        self.conversationIdentifier = conversationIdentifier
        self.webAvailable = webAvailable
        self.toolCatalog = toolCatalog
        self.context = context
    }
}

public enum V2AgentAction: Equatable, Sendable {
    case answer(text: String)
    case webSearch(query: String)
    case webRead(url: URL)
    case localSearch(query: String)
    case plan(query: String)
    case schedule(query: String)
    case toolCall(V2AgentToolCall)
}

public struct V2AgentModelResult: Equatable, Sendable {
    public var additionalToolCalls: [V2AgentToolCall]
    public var continuationMessage: Data?
    public var continueAfterTool: Bool
    public var action: V2AgentAction
    public var providerLabel: String
    public var model: String
    public var requestID: String?
    public var responseID: String?
    public var promptTokens: Int?
    public var completionTokens: Int?
    public var totalTokens: Int?

    public init(
        action: V2AgentAction,
        providerLabel: String,
        model: String,
        requestID: String? = nil,
        responseID: String? = nil,
        promptTokens: Int? = nil,
        completionTokens: Int? = nil,
        totalTokens: Int? = nil,
        continueAfterTool: Bool = false,
        additionalToolCalls: [V2AgentToolCall] = [],
        continuationMessage: Data? = nil
    ) {
        self.additionalToolCalls = additionalToolCalls
        self.continuationMessage = continuationMessage
        self.continueAfterTool = continueAfterTool
        self.action = action
        self.providerLabel = providerLabel
        self.model = model
        self.requestID = requestID
        self.responseID = responseID
        self.promptTokens = promptTokens
        self.completionTokens = completionTokens
        self.totalTokens = totalTokens
    }
}

public protocol V2AgentClient: Sendable {
    var providerLabel: String { get }
    func respond(_ request: V2AgentRequest) async throws -> V2AgentModelResult
}

public enum V2AgentClientError: Error, Equatable, LocalizedError, Sendable {
    case invalidConfiguration(String)
    case requestFailed(statusCode: Int, message: String)
    case missingOutput
    case refused(String)
    case invalidOutput(String)

    public var errorDescription: String? {
        switch self {
        case let .invalidConfiguration(message):
            "AI 配置不可用：\(message)"
        case let .requestFailed(statusCode, message):
            "AI 请求失败（\(statusCode)）：\(message)"
        case .missingOutput:
            "AI 没有返回可用内容。"
        case let .refused(message):
            "AI 无法完成这次请求：\(message)"
        case let .invalidOutput(message):
            "AI 返回的操作无法使用：\(message)"
        }
    }
}

